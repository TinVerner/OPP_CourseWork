SET client_encoding = 'UTF8';

CREATE TYPE order_status AS ENUM (
    'pending', 'accepted', 'preparing', 'delivering',
    'ready_for_pickup', 'done', 'canceled'
);
CREATE TYPE delivery_type AS ENUM ('pickup', 'courier');

CREATE TABLE roles (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(64) NOT NULL
);

CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         varchar(100) NOT NULL,
    phone         varchar(32)  NOT NULL,
    email         varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,
    firstname     varchar(100) NOT NULL,
    lastname      varchar(100) NOT NULL,
    address       varchar(255),
    created_at    timestamptz  NOT NULL,
    is_blocked    boolean      NOT NULL DEFAULT false,
    role_id       integer      NOT NULL REFERENCES roles(id)
);
CREATE UNIQUE INDEX ix_users_login ON users(login);
CREATE UNIQUE INDEX ix_users_email ON users(email);
CREATE UNIQUE INDEX ix_users_phone ON users(phone);

CREATE TABLE categories (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint,
    name      varchar(128) NOT NULL
);

CREATE TABLE ingredients (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(128) NOT NULL,
    note          varchar(255),
    is_spicy      boolean NOT NULL DEFAULT false,
    is_vegetarian boolean NOT NULL DEFAULT false
);

CREATE TABLE menu_items (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id   bigint REFERENCES categories(id),
    image_url     text,
    item_type     text NOT NULL,
    name          varchar(255) NOT NULL,
    description   text,
    price         numeric(10,2) NOT NULL,
    protein_g     numeric(6,2),
    fat_g         numeric(6,2),
    carbs_g       numeric(6,2),
    calories_kcal numeric(7,2),
    user_id       bigint REFERENCES users(id),
    created_at    timestamptz NOT NULL
);

CREATE TABLE ingredients_roll (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roll_id       bigint NOT NULL REFERENCES menu_items(id),
    ingredient_id bigint NOT NULL REFERENCES ingredients(id)
);

CREATE TABLE menu_set_components (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id  bigint NOT NULL REFERENCES menu_items(id),
    item_id bigint NOT NULL REFERENCES menu_items(id),
    qty     integer NOT NULL
);

CREATE TABLE orders (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          bigint REFERENCES users(id),
    status           order_status NOT NULL,
    customer_name    varchar(128),
    customer_phone   varchar(32),
    delivery_type    delivery_type NOT NULL,
    customer_address varchar(255),
    delivery_time    timestamptz,
    comment          varchar(255),
    total_price      numeric(10,2) NOT NULL,
    created_at       timestamptz NOT NULL,
    delivered_at     timestamptz
);

CREATE TABLE order_items (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     bigint NOT NULL REFERENCES orders(id),
    menu_item_id bigint NOT NULL REFERENCES menu_items(id),
    qty          integer NOT NULL,
    price        numeric(10,2) NOT NULL
);

